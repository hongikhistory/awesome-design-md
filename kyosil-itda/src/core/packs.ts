export const packFor = (studio: StudioId) => PACKS.find((p) => p.studio === studio) ?? PACKS[PACKS.length - 1];

/** The pack whose keywords appear in a message, if any. */
export function findPack(text: string): Pack | undefined {
  const t = text.toLowerCase();
  return PACKS.find((p) => p.keys.some((k) => t.includes(k.toLowerCase())));
}

export const withTeacher = (plan: string, teacher: string) => plan.replace("{teacher}", teacher);

