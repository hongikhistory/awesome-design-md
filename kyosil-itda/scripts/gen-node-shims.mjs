// Regenerates src/node-shims/{builtins,crypto,zlib,native}.js from the names kordoc imports.
// Run after upgrading kordoc:  node scripts/gen-node-shims.mjs
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { builtinModules } from "node:module";
import { join } from "node:path";

const dist = new URL("../node_modules/kordoc/dist/", import.meta.url).pathname;
const out = new URL("../src/node-shims/", import.meta.url).pathname;
const files = readdirSync(dist).filter((f) => f.endsWith(".js")).map((f) => readFileSync(join(dist, f), "utf8"));
const esc = (x) => x.replace(/[.*+?^${}()|[\]\\/]/g, "\\$&");
function namesFrom(mods) {
  const re = new RegExp(`import\\s*\\{([^}]*)\\}\\s*from\\s*["'](?:node:)?(?:${mods.map(esc).join("|")})["']`, "g");
  const names = new Set();
  for (const src of files) for (const m of src.matchAll(re)) for (const part of m[1].split(",")) {
    const n = part.trim().split(/\s+as\s+/)[0].trim();
    if (n) names.add(n);
  }
  return [...names].sort();
}
const header = "// Browser stand-in for Node built-ins used by kordoc (generated by scripts/gen-node-shims.mjs).\n// Functions kordoc only needs on a file system (CLI, OCR, native image tools) throw when called.\n";
const fail = 'const fail=(n)=>()=>{throw new Error(n+" is not available in the browser")};';
const special = new Set(["zlib", "crypto", "child_process", "worker_threads", "buffer"]);
const generic = builtinModules.filter((b) => !b.startsWith("_") && !special.has(b));
const impl = {
  join: '(...a)=>a.filter(Boolean).join("/")', dirname: '(p)=>String(p).split("/").slice(0,-1).join("/")',
  basename: '(p,e)=>{const b=String(p).split("/").pop();return e&&b.endsWith(e)?b.slice(0,-e.length):b}',
  extname: '(p)=>{const m=/\\.[^./]+$/.exec(String(p));return m?m[0]:""}', resolve: '(...a)=>a.join("/")',
  isAbsolute: '(p)=>String(p).startsWith("/")', relative: "(a,b)=>b", normalize: "(p)=>p", sep: '"/"', delimiter: '":"',
  fileURLToPath: "(u)=>String(u)", pathToFileURL: "(p)=>({href:String(p)})", existsSync: "()=>false", tmpdir: '()=>"/tmp"',
  homedir: '()=>"/"', hostname: '()=>"browser"', platform: '()=>"browser"', promisify: "(f)=>f", inspect: "(x)=>String(x)",
  format: '(...a)=>a.join(" ")', constants: "{}", TextDecoder: "globalThis.TextDecoder", TextEncoder: "globalThis.TextEncoder",
  createRequire: '()=>{const r=(id)=>{if(id==="cfb"&&globalThis.__kordocCfb)return globalThis.__kordocCfb;throw new Error("require("+id+") is not available in the browser")};r.resolve=(id)=>{throw new Error("cannot resolve "+id)};return r;}',
  EventEmitter: "class{on(){return this}once(){return this}emit(){return false}off(){return this}}",
};
const emit = (file, names, extra, pre = "") => {
  const lines = [header + pre + fail, ...names.map((n) => `export const ${n}=${extra[n] ?? `fail("${n}")`};`), `export default {${names.join(",")}};`];
  writeFileSync(join(out, file), lines.join("\n") + "\n");
};
emit("builtins.js", namesFrom(generic), impl);
emit("crypto.js", namesFrom(["crypto"]), { randomUUID: "()=>globalThis.crypto.randomUUID()", randomBytes: "(n)=>globalThis.crypto.getRandomValues(new Uint8Array(n))" });
const z = [...new Set([...namesFrom(["zlib"]), "inflateRawSync", "inflateSync", "deflateRawSync", "deflateSync", "constants"])].sort();
emit("zlib.js", z, { inflateRawSync: "(b)=>pako.inflateRaw(b)", inflateSync: "(b)=>pako.inflate(b)", deflateRawSync: "(b,o)=>pako.deflateRaw(b,o)", deflateSync: "(b,o)=>pako.deflate(b,o)", constants: "{}" }, 'import pako from "pako";\n');
const nat = namesFrom(["child_process", "worker_threads"]);
writeFileSync(join(out, "native.js"), header + 'const fail=()=>{throw new Error("native module not available in browser")};\nconst P=new Proxy(fail,{get:(_t,k)=>k==="__esModule"?false:P,apply:fail});\nexport default P;\n' + nat.map((n) => `export const ${n}=P;`).join("\n") + "\n");
console.log("node shims regenerated");
